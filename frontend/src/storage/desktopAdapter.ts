// Desktop storage adapter (ticket F5, approach #3). Backs the StorageProvider with
// better-sqlite3-multiple-ciphers — a native, SYNCHRONOUS SQLite that, unlike the web sql.js build,
// ships FTS5. That is the whole reason this adapter exists: the packaged desktop app gets the real
// lexical leg of hybrid retrieval (memories_fts MATCH … bm25) that the web path silently lacks.
//
// This module lives in src so it is typechecked with the rest of the renderer, but better-sqlite3 is
// loaded through a LAZY, indirect require (loadDatabaseCtor) — there is no static import of the
// native module, so the Vite renderer/PWA build never bundles it. It is loaded ONLY in the Electron
// MAIN process (which registers this adapter via registerDesktopStorage) and is externalized +
// asar-unpacked by the desktop build (electron.vite externalizeDepsPlugin + electron-builder
// asarUnpack) so the .node binary is loadable in the packaged app.
//
// ── Encryption + secret handling (parity with db.ts's Android Keystore invariant) ────────────────
// On device the SQLCipher passphrase is generated by a CSPRNG and stored in the OS-backed secret
// store, NEVER in JS/WebView storage (db.ts documents this for AndroidKeyStore). The desktop
// equivalent: the key is generated and stored in the Electron MAIN process via safeStorage
// (Keychain on macOS / DPAPI on Windows / libsecret on Linux) and applied with
// `PRAGMA key`/`PRAGMA cipher='sqlcipher'` before the first query. The renderer never sees the key
// and it is never written to localStorage. The key plumbing is supplied by the caller (the main
// process) as openOptions.key; this module only applies it — it does not invent a storage location,
// keeping the single-source-of-truth invariant intact.
import { runMigrations, type MigrateDriver } from "./migrate";
import type { RunResult, StorageProvider } from "./StorageProvider";

/** The slice of the better-sqlite3 Database surface this adapter uses. Declared structurally so the
 *  module needs no @types/better-sqlite3 dependency and the unit test can pass a real instance. */
export interface BetterSqliteDb {
  prepare(sql: string): {
    all(...params: any[]): any[];
    run(...params: any[]): { changes: number; lastInsertRowid: number | bigint };
  };
  exec(sql: string): void;
  pragma(source: string, options?: { simple?: boolean }): any;
  close(): void;
}

/** Constructor shape of the `better-sqlite3(-multiple-ciphers)` default export. */
export type DatabaseCtor = new (filename: string, options?: Record<string, unknown>) => BetterSqliteDb;

export interface DesktopStorageOptions {
  /** Absolute path to the on-disk DB file. Use ":memory:" only for tests. */
  filename: string;
  /** Injected Database constructor — defaults to the real better-sqlite3-multiple-ciphers. Tests pass
   *  a plain in-memory better-sqlite3 here so they never touch the native cipher / a real file. */
  Database?: DatabaseCtor;
  /** SQLCipher hex passphrase, sourced by the MAIN process from safeStorage (see file header). When
   *  present the adapter runs `PRAGMA cipher='sqlcipher'` + `PRAGMA key='…'` before any query. Omit
   *  for :memory: / tests (SQLCipher can't key an in-memory DB). */
  key?: string;
}

/** Lazily resolve the native better-sqlite3-multiple-ciphers constructor. Only reached on the
 *  main-process path when no Database was injected (tests always inject one). */
function loadDatabaseCtor(): DatabaseCtor {
  // Indirect require so this module typechecks under the renderer's src tsconfig without @types/node;
  // it only ever runs in the Electron MAIN process (the renderer never imports this module).
  const req = eval("require") as NodeRequire;
  const mod = req("better-sqlite3-multiple-ciphers");
  return (mod.default ?? mod) as DatabaseCtor;
}

/**
 * Open (and migrate) the desktop DB and return a StorageProvider over it. Synchronous better-sqlite3
 * is wrapped in async methods so the StorageProvider shape matches db.ts exactly (q → Promise<row[]>,
 * run → Promise<{lastId, changes}>). Migrations run the REAL schema.ts MIGRATIONS via runMigrations,
 * bringing PRAGMA user_version to SCHEMA_VERSION and creating memories_fts (FTS5).
 */
export function openDesktopStorage(options: DesktopStorageOptions): StorageProvider {
  const Ctor = options.Database ?? loadDatabaseCtor();
  const db = new Ctor(options.filename);

  if (options.key) {
    // SQLCipher: select the cipher then apply the key BEFORE any other statement. The key never
    // leaves the main process; the renderer that ultimately calls q/run only ever sees rows.
    db.pragma(`cipher='sqlcipher'`);
    db.pragma(`key='${options.key.replace(/'/g, "''")}'`);
  }
  db.pragma("foreign_keys = ON");

  const driver: MigrateDriver = {
    exec: (sql) => db.exec(sql),
    getUserVersion: () => Number(db.pragma("user_version", { simple: true })),
    setUserVersion: (v) => db.exec(`PRAGMA user_version=${v};`),
    columns: (t) => (db.prepare(`PRAGMA table_info(${t})`).all() as any[]).map((r) => String(r.name)),
  };
  runMigrations(driver);

  return adapt(db);
}

/** Wrap an already-open better-sqlite3 Database in the StorageProvider shape. Exposed for the unit
 *  test (which constructs + migrates its own in-memory DB) and reused by openDesktopStorage. */
export function adapt(db: BetterSqliteDb): StorageProvider {
  // The native bridge (like the Capacitor one in db.ts) rejects `undefined` bound params; coerce to
  // null so a caller passing an optional field through behaves the same on both backends.
  const safe = (params: any[]) => params.map((p) => (p === undefined ? null : p));

  return {
    kind: "desktop",
    async q<T = any>(sql: string, params: any[] = []): Promise<T[]> {
      return db.prepare(sql).all(...safe(params)) as T[];
    },
    async run(sql: string, params: any[] = []): Promise<RunResult> {
      const r = db.prepare(sql).run(...safe(params));
      return { lastId: Number(r.lastInsertRowid), changes: r.changes };
    },
    async exec(sql: string): Promise<void> {
      db.exec(sql);
    },
    async persist(): Promise<void> {
      // better-sqlite3 writes are durable on commit; nothing to flush (mirrors db.ts's native no-op).
    },
  };
}
